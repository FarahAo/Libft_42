#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*p;
	size_t			i;

	p = (unsigned char *)s;
	i = 0;
	while (n)
	{
		p[i] = c;
		n--;
		i++;
	}
	return (s);
}
